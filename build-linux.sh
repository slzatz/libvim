#!/usr/bin/env bash
#
# Build libvim.a on Linux. Run it with no arguments:
#
#   ./build-linux.sh
#
# Optional:
#   --clean   discard existing objects and rebuild everything
#   --tests   also build and run the API test suite
#
# Configuring is handled automatically: this script runs ./configure only when
# the checkout has never been configured or when the required flags have
# changed, and clears the stale autoconf cache that would otherwise abort the
# reconfigure. See CLAUDE.md for details.

set -euo pipefail

CLEAN=0
TESTS=0
for arg in "$@"; do
	case "$arg" in
	--clean) CLEAN=1 ;;
	--tests) TESTS=1 ;;
	-h | --help)
		sed -n '3,14p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "error: unknown option '$arg' (try --help)" >&2
		exit 1
		;;
	esac
done

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/src"

if [ "$(uname -s)" != "Linux" ]; then
	echo "error: this is the Linux script; on macOS run ./build-macos.sh" >&2
	exit 1
fi

# Header check rather than a package-manager query, so this works regardless of
# distro. curses.h comes from libtinfo-dev/ncurses-devel/ncurses.
if ! printf '#include <curses.h>\nint main(void){return 0;}\n' |
	cc -E -x c - >/dev/null 2>&1; then
	echo "error: ncurses development headers not found." >&2
	echo "       Debian/Ubuntu: sudo apt install libtinfo-dev libacl1-dev" >&2
	echo "       Fedora/RHEL:   sudo dnf install ncurses-devel libacl-devel" >&2
	echo "       Arch:          sudo pacman -S ncurses acl" >&2
	exit 1
fi

# -fPIC so the archive can be linked into a shared object or a Go binary.
#
# The two -Wno-error flags are for ./configure, not the compile (the Makefile's
# WARN_FLAGS covers that). GCC 14 made implicit int and implicit function
# declarations hard errors, and configure's probe programs use both. Without
# the first, every terminal-library probe fails and configure stops with
# "checking for tgetent()... NOT FOUND!"; without the second, the SVR4 pty
# probe fails silently and HAVE_SVR4_PTYS is dropped from auto/config.h. With
# both, config.h matches a -fpermissive configure (verified on GCC 16.2).
WANT_CFLAGS="-fPIC -Wno-error=implicit-int -Wno-error=implicit-function-declaration"

cd "$SRC"

have_cflags=""
if [ -f auto/config.mk ]; then
	have_cflags="$(sed -n 's/^CFLAGS[[:space:]]*=[[:space:]]*//p' auto/config.mk | head -1)"
fi
norm() { echo "$1" | tr -s '[:space:]' ' ' | sed 's/^ //; s/ $//'; }

if [ ! -f auto/config.mk ] || [ "$(norm "$have_cflags")" != "$(norm "$WANT_CFLAGS")" ]; then
	echo "==> Configuring"
	# Autoconf refuses to re-run when cached flags differ; the cache is
	# regenerated by the configure call below.
	rm -f auto/config.cache
	./configure --disable-selinux CFLAGS="$WANT_CFLAGS"
else
	echo "==> Already configured, skipping ./configure"
fi

if [ "$CLEAN" -eq 1 ]; then
	echo "==> Cleaning objects"
	rm -f objects/*.o libvim.a
fi

JOBS="$(nproc 2>/dev/null || echo 4)"
echo "==> Building libvim.a (-j$JOBS)"
make libvim.a "-j$JOBS"

echo
echo "Built: $SRC/libvim.a"

if [ "$TESTS" -eq 1 ]; then
	# DEST_BIN redirects the test rule's install step away from /bin, which is
	# not writable and would otherwise fail the build after a successful link.
	staging="$(mktemp -d)"
	trap 'rm -rf "$staging"' EXIT

	echo
	echo "==> Building and running API tests"
	failed=0
	for t in apitest/*.c; do
		name="$(basename "$t" .c)"
		make "apitest/$name.test.exe" DEST_BIN="$staging" >/dev/null
		if (cd apitest && "./$name.test.exe" >/dev/null 2>&1); then
			echo "  PASS  $name"
		else
			echo "  FAIL  $name"
			failed=1
		fi
	done
	[ "$failed" -eq 0 ] || { echo "error: some API tests failed" >&2; exit 1; }
	echo "All API tests passed."
fi
