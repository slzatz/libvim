#!/usr/bin/env bash
#
# Build libvim.a on macOS. Run it with no arguments:
#
#   ./build-macos.sh
#
# Optional:
#   --clean   discard existing objects and rebuild everything
#   --tests   also build and run the API test suite
#
# Configuring is handled automatically: this script runs ./configure only when
# the checkout has never been configured or when the required flags have
# changed, and clears the stale autoconf cache that would otherwise abort the
# reconfigure. See CLAUDE.md for what the individual -Wno-error flags are for.

set -euo pipefail

CLEAN=0
TESTS=0
for arg in "$@"; do
	case "$arg" in
	--clean) CLEAN=1 ;;
	--tests) TESTS=1 ;;
	-h | --help)
		sed -n '3,14p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		echo "error: unknown option '$arg' (try --help)" >&2
		exit 1
		;;
	esac
done

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/src"

if [ "$(uname -s)" != "Darwin" ]; then
	echo "error: this is the macOS script; on Linux run ./build-linux.sh" >&2
	exit 1
fi

if ! command -v brew >/dev/null 2>&1; then
	echo "error: Homebrew is required but was not found." >&2
	echo "       Install it from https://brew.sh, then re-run this script." >&2
	exit 1
fi

# Resolved rather than hardcoded, so this works on both Apple Silicon
# (/opt/homebrew) and Intel (/usr/local).
missing=""
for pkg in ncurses gettext; do
	brew --prefix "$pkg" >/dev/null 2>&1 || missing="$missing $pkg"
done
if [ -n "$missing" ]; then
	echo "error: missing Homebrew package(s):$missing" >&2
	echo "       Run: brew install$missing" >&2
	exit 1
fi

NCURSES="$(brew --prefix ncurses)"
GETTEXT="$(brew --prefix gettext)"
BREW="$(brew --prefix)"

# Every one of these is load-bearing on current clang, which rejects legacy C
# that this codebase is full of.
WARN=(
	-Wno-error=implicit-function-declaration
	-Wno-error=implicit-int
	-Wno-error=int-conversion
	-Wno-error=incompatible-function-pointer-types
	-Wno-error=unused-but-set-variable
	-Wno-error=deprecated-non-prototype
	-Wno-error=implicit-int-float-conversion
)
WANT_CFLAGS="-I$NCURSES/include -I$BREW/include ${WARN[*]}"
WANT_LDFLAGS="-L$NCURSES/lib -L$BREW/lib"

cd "$SRC"

# Reconfigure only when necessary. Comparing against the CFLAGS recorded in the
# generated config.mk means adding a flag to WARN above automatically triggers a
# reconfigure on the next run.
have_cflags=""
if [ -f auto/config.mk ]; then
	have_cflags="$(sed -n 's/^CFLAGS[[:space:]]*=[[:space:]]*//p' auto/config.mk | head -1)"
fi
norm() { echo "$1" | tr -s '[:space:]' ' ' | sed 's/^ //; s/ $//'; }

if [ ! -f auto/config.mk ] || [ "$(norm "$have_cflags")" != "$(norm "$WANT_CFLAGS")" ]; then
	echo "==> Configuring (ncurses: $NCURSES)"
	# Autoconf refuses to re-run when cached flags differ; the cache is
	# regenerated by the configure call below.
	rm -f auto/config.cache
	./configure --disable-selinux --with-tlib=ncurses \
		CFLAGS="$WANT_CFLAGS" LDFLAGS="$WANT_LDFLAGS"
else
	echo "==> Already configured, skipping ./configure"
fi

if [ "$CLEAN" -eq 1 ]; then
	echo "==> Cleaning objects"
	rm -f objects/*.o libvim.a
fi

JOBS="$(sysctl -n hw.ncpu 2>/dev/null || echo 4)"
echo "==> Building libvim.a (-j$JOBS)"
make libvim.a "-j$JOBS"

echo
echo "Built: $SRC/libvim.a"

if [ "$TESTS" -eq 1 ]; then
	# The test rule links against libintl, whose directory the Makefile does not
	# add. DEST_BIN redirects the rule's install step away from /bin, which is
	# not writable and would otherwise fail the build after a successful link.
	staging="$(mktemp -d)"
	trap 'rm -rf "$staging"' EXIT

	echo
	echo "==> Building and running API tests"
	failed=0
	for t in apitest/*.c; do
		name="$(basename "$t" .c)"
		make "apitest/$name.test.exe" \
			EXTRA_LIBS="-L$GETTEXT/lib" DEST_BIN="$staging" >/dev/null
		if (cd apitest && "./$name.test.exe" >/dev/null 2>&1); then
			echo "  PASS  $name"
		else
			echo "  FAIL  $name"
			failed=1
		fi
	done
	[ "$failed" -eq 0 ] || { echo "error: some API tests failed" >&2; exit 1; }
	echo "All API tests passed."
fi
